def _parse_hosts(val):
    hosts = []
    for h in val.split(","):
        h = h.strip()
        if not h:
            continue
        if h.startswith("*."):
            hosts.append(h[1:])  # Django uses leading dot (.onrender.com) for wildcard subdomains
        hosts.append(h)
    return list(set(hosts)) if hosts else ["*"]

